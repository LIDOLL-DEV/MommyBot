import assert from "node:assert/strict";
import { createServer } from "node:http";
import { mkdir } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { dressupFixture } from "./fixtures/dressup.mjs";

if (!process.env.PUPPETEER_MODULE || !process.env.CHROME_PATH) throw new Error("Set PUPPETEER_MODULE and CHROME_PATH to local browser tools.");
const puppeteer = (await import(pathToFileURL(process.env.PUPPETEER_MODULE).href)).default;
const f = dressupFixture(); let browser, server;
try {
  f.seed(f.diapers, "ribbon-bouquet"); f.seed(f.diapers, "cloud-tapes");
  for (const item of f.catalog.clothes.slice(0, 6)) f.seed(f.clothes, item.id);
  server = createServer(async (req, res) => { if (!await f.web(req, res)) { res.writeHead(404); res.end(); } });
  await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
  f.config.origin = `http://127.0.0.1:${server.address().port}`;
  browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH, headless: true, pipe: true });
  console.log("Browser launched.");
  const page = await browser.newPage(), errors = [], failures = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (/Content Security Policy|Refused to/i.test(message.text())) errors.push(message.text()); });
  page.on("response", response => { if (response.status() >= 400 && response.url().includes("/art/")) failures.push(response.url()); });
  await page.setCookie({ name: "diaper_session", value: f.token, url: f.config.origin });
  await page.setViewport({ width: 1440, height: 1150 });
  await page.goto(`${f.config.origin}/littlepottchi/`);
  console.log("Littlepottchi loaded.");
  await page.waitForFunction(() => !document.getElementById("game").hidden);
  assert.equal(await page.$eval("#slot", select => [...select.options].some(option => option.value === "underwear")), false);
  await page.click('[data-view="diapers"]');
  await page.evaluate(() => [...document.querySelectorAll(".item")].find(card => card.textContent.includes("Ribbon Bouquet")).querySelector("button").click());
  await page.waitForFunction(() => document.getElementById("stance").textContent.includes("Wide stance"));
  assert.equal(f.doll.snapshot(f.user).base, "DQ_Base_2.png");
  await page.click("summary");
  await page.select("#shape", "angular");
  await page.select("#hair", "TQ_Hair_4_Pink.png");
  await page.click('#appearance button');
  await page.waitForFunction(() => !document.querySelector('#appearance button').disabled);
  assert.equal(f.doll.snapshot(f.user).base, "DQ_Base_4.png");
  await page.click('[data-care="feed"]');
  await page.waitForFunction(() => document.getElementById("bond").textContent.includes("2 care"));
  await page.select("#food", "lunch");
  await page.click('[data-care="water"]');
  await page.waitForFunction(() => document.getElementById("bond").textContent.includes("3 care"));
  await page.click('[data-care="play"]');
  await page.waitForFunction(() => document.getElementById("activity-status").textContent.includes("Playing"));
  f.now += 120000;
  await page.click("#refresh");
  await page.waitForFunction(() => document.getElementById("activity-status").textContent.includes("finished"));
  await page.click("#pet-reminders");
  await page.waitForFunction(() => !document.getElementById("pet-reminders").disabled);
  assert.equal(f.doll.snapshot(f.user).player.care.reminders,true);
  const beforeLeak = f.doll.snapshot(f.user);
  f.now = beforeLeak.player.care.nextWettingAt + (beforeLeak.diaper.bulk - 1) * beforeLeak.player.care.interval;
  await page.click("#refresh");
  await page.waitForFunction(() => document.getElementById("leak-status").textContent.includes("Leaking"));
  await page.select("#replacement", "cloud-tapes");
  await page.click('[data-care="change"]');
  await page.waitForFunction(() => document.getElementById("leak-status").textContent.includes("Fresh"));
  assert.equal(f.doll.snapshot(f.user).stance,"narrow");
  await page.select("#replacement", "ribbon-bouquet");
  await page.click('[data-care="change"]');
  await page.waitForFunction(() => document.getElementById("stance").textContent.includes("Wide stance"));
  await page.waitForNetworkIdle();
  console.log("Wide stance, split hair and care checked.");
  await mkdir("data/dressup-review", { recursive: true });
  await page.screenshot({ path: "data/dressup-review/littlepottchi-desktop.png", fullPage: true });
  await page.evaluate(() => [...document.querySelectorAll(".item")].find(card => card.textContent.includes("Cloud Tapes")).querySelector("button").click());
  await page.waitForFunction(() => document.getElementById("stance").textContent.includes("Regular stance"));
  assert.equal(f.doll.snapshot(f.user).base, "TQ_Base_2.png");
  await page.goto(`${f.config.origin}/clothes/`);
  await page.waitForFunction(() => !document.getElementById("roll").disabled);
  await page.click("#roll");
  await page.waitForSelector("#reveal[open]");
  console.log("Clothing roll revealed.");
  assert.equal(f.receipts.size, 1); assert.equal(f.coins, 997);
  await page.click("#prize-done");
  await page.click('[data-view="catalog"]');
  await page.waitForNetworkIdle();
  assert.equal(await page.$$eval(".item", items => items.length), 36);
  assert.match(await page.$eval("#gallery-status", el => el.textContent), new RegExp(`of ${f.catalog.clothes.length} pieces`));
  const firstTitle = await page.$eval(".item h3", el => el.textContent);
  await page.click("#next-page");
  assert.notEqual(await page.$eval(".item h3", el => el.textContent), firstTitle);
  assert.match(await page.$eval("#gallery-status", el => el.textContent), /^37–72/);
  await page.select("#slot", "gloves");
  assert.equal(await page.$$eval(".item", items => items.length), f.catalog.clothes.filter(i => i.slot === "gloves").length);
  assert.match(await page.$eval("#gallery-status", el => el.textContent), /^1–/);
  await page.select("#slot", "");
  await page.waitForNetworkIdle();
  await page.screenshot({ path: "data/dressup-review/clothes-desktop.png", fullPage: true });
  f.lose = true;
  await page.click("#roll");
  await page.waitForFunction(() => !document.getElementById("pending").hidden && !document.getElementById("retry").disabled);
  await page.reload();
  await page.waitForFunction(() => !document.getElementById("pending").hidden && !document.getElementById("retry").disabled);
  await page.click("#retry"); await page.waitForSelector("#reveal[open]");
  assert.equal(f.receipts.size, 2); assert.equal(f.coins, 994);
  await page.click("#prize-done");
  await page.setViewport({ width: 390, height: 844 });
  await page.click('[data-view="owned"]');
  await page.waitForNetworkIdle();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "No horizontal overflow at phone width");
  await page.screenshot({ path: "data/dressup-review/clothes-mobile.png", fullPage: true });
  await page.goto(`${f.config.origin}/littlepottchi/`);
  await page.waitForFunction(() => !document.getElementById("game").hidden);
  await page.waitForNetworkIdle();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Pet care fits at phone width");
  await page.screenshot({ path: "data/dressup-review/littlepottchi-mobile.png", fullPage: true });
  assert.deepEqual(errors, []); assert.deepEqual(failures, []);
  await page.click("#logout");
  await page.waitForFunction(() => !document.getElementById("signin").hidden);
  console.log("Browser passed: login, catalog, stances, food/water, timed play, leaks/replacements, pet reminders, roll/retry, both mobile screens and logout; no art or script/CSP errors.");
} finally {
  await browser?.close();
  if (server) await new Promise(resolve => server.close(resolve));
  await f.close();
}
